class InMemoryReview(Review):
    """Review that works with in-memory data instead of database."""

    def __init__(self, **data):
        super().__init__(**data)
        self._article_obj: Article | None = None
        self._publisher_obj: Publisher | None = None
        self._appearances_list: list[Appearance] = []

    @property
    async def article(self) -> Article | None:
        return self._article_obj

    @property
    async def publisher(self) -> Publisher | None:
        return self._publisher_obj

    @property
    async def appearances(self) -> list[Appearance]:
        return self._appearances_list

    async def save_to_db(self):
        """No-op: don't save to database."""
        pass

    async def set_stage(self, stage: int) -> None:
        """No-op: don't update database."""
        self.stage = stage


class InMemoryClaim(Claim):
    """Claim that works with in-memory data instead of database."""

    def __init__(self, **data):
        super().__init__(**data)
        self._reviews_list: list[Review] = []
        self._appearances_list: list[Appearance] = []
        self._verdicts_list: list[Verdict] = []

    @property
    async def reviews(self) -> list[Review]:
        return self._reviews_list

    @property
    async def appearances(self) -> list[Appearance]:
        return self._appearances_list

    @property
    async def current_verdict(self) -> Verdict | None:
        return self._verdicts_list[0] if self._verdicts_list else None

    async def save_to_db(self):
        """No-op: don't save to database."""
        pass


class InMemoryVerdict(Verdict):
    """Verdict that works with in-memory storage."""

    async def save_to_db(self):
        """No-op: don't save to database."""
        pass


