def load_data_from_zip(zip_path: Path) -> tuple[dict, dict, Path]:
    """
    Load pipeline data and annotations from zip file.

    Args:
        zip_path: Path to the export zip file

    Returns:
        Tuple of (pipeline_data, annotations_data, temp_media_dir)
    """
    logger.info(f"Loading data from {zip_path}")

    with ZipFile(zip_path, 'r') as zf:
        # Load pipeline data
        with zf.open('pipeline_data.json') as f:
            pipeline_data = json.load(f)

        # Load annotations
        with zf.open('annotations.json') as f:
            annotations_data = json.load(f)

        # Extract media files to temp directory
        temp_dir = Path(tempfile.mkdtemp(prefix='veritas_compare_'))
        media_dir = temp_dir / 'media'

        logger.info(f"Extracting media files to {media_dir}")
        for name in zf.namelist():
            if name.startswith('media/'):
                zf.extract(name, temp_dir)

        logger.info(f"Loaded {len(pipeline_data.get('claims', []))} claims")
        logger.info(f"Loaded annotations for {len(annotations_data.get('grouped_by_claim', {}))} claims")

    return pipeline_data, annotations_data, media_dir.parent


def parse_date(date_str: str | None) -> date | datetime | None:
    """Parse ISO date string to date or datetime object."""
    if not date_str:
        return None
    try:
        # Try parsing as datetime first
        return datetime.fromisoformat(date_str)
    except ValueError:
        try:
            # Try parsing as date
            return date.fromisoformat(date_str)
        except ValueError:
            return None


def build_in_memory_objects(pipeline_data: dict, temp_dir: Path) -> dict[int, InMemoryClaim]:
    """
    Build in-memory object graph from pipeline data.

    Args:
        pipeline_data: Dictionary with claims, reviews, articles, publishers, appearances
        temp_dir: Temporary directory containing media files

    Returns:
        Dictionary mapping claim_id to InMemoryClaim instances
    """
    logger.info("Building in-memory object graph")

    # First pass: build a mapping of article URLs to publisher_ids and review_ids
    # by examining reviews
    article_metadata = defaultdict(lambda: {'publisher_id': None, 'review_ids': set()})
    for review_data in pipeline_data.get('reviews', []):
        url = str(review_data['url'])
        article_metadata[url]['review_ids'].add(review_data['id'])
        if review_data.get('publisher_id'):
            article_metadata[url]['publisher_id'] = review_data['publisher_id']

    # Build lookup dictionaries
    articles_by_url = {}
    for article_data in pipeline_data.get('articles', []):
        url = str(article_data['url'])
        metadata = article_metadata[url]

        article = Article(
            id=article_data['id'],
            url=article_data['url'],
            publisher_id=metadata['publisher_id'] or 0,  # Default to 0 if missing
            review_ids=metadata['review_ids'],
            scraped_page=article_data.get('scraped_content'),
            extracted_article=article_data.get('extracted_content'),
            title=article_data.get('headline') or article_data.get('title'),
        )
        articles_by_url[url] = article

    publishers_by_id = {}
    for publisher_data in pipeline_data.get('publishers', []):
        # Publisher requires at least one signatory status - set to NOT_A_SIGNATORY if not present
        from veritas.common.publisher import SignatoryStatus

        publisher = Publisher(
            id=publisher_data['id'],
            name=publisher_data['name'],
            url=publisher_data.get('url'),
            ifcn_status=publisher_data.get('ifcn_status', SignatoryStatus.NOT_A_SIGNATORY),
            efcsn_status=publisher_data.get('efcsn_status'),
            expires=parse_date(publisher_data.get('expires')),
            country=publisher_data.get('country'),
            language=publisher_data.get('language'),
        )
        publishers_by_id[publisher.id] = publisher

    appearances_by_id = {}
    for appearance_data in pipeline_data.get('appearances', []):
        # Convert scraped_content to MultimodalSequence if it's a string
        scraped_content = appearance_data.get('scraped_content')
        if scraped_content and isinstance(scraped_content, str):
            scraped_content = MultimodalSequence(scraped_content)

        appearance = Appearance(
            id=appearance_data['id'],
            url=appearance_data['url'],
            archive_url=appearance_data.get('archive_url'),
            published=parse_date(appearance_data.get('published')),
            author_name=appearance_data.get('author_name'),
            author_url=appearance_data.get('author_url'),
            scraped_content=scraped_content,
            platform=appearance_data.get('platform'),
        )
        appearances_by_id[appearance.id] = appearance

    # Build reviews
    reviews_by_id = {}
    for review_data in pipeline_data.get('reviews', []):
        review = InMemoryReview(
            id=review_data['id'],
            url=review_data['url'],
            raw_claim=review_data['raw_claim'],
            raw_rating=review_data.get('raw_rating'),
            raw_claimant_name=review_data.get('raw_claimant_name'),
            raw_claimant_url=review_data.get('raw_claimant_url'),
            raw_claim_date=parse_date(review_data.get('raw_claim_date')),
            raw_publisher_name=review_data.get('raw_publisher_name'),
            raw_publisher_url=review_data.get('raw_publisher_url'),
            published=parse_date(review_data.get('published')),
            author_name=review_data.get('author_name'),
            author_url=review_data.get('author_url'),
            modified=parse_date(review_data.get('modified')),
            language=review_data.get('language'),
            claim_id=review_data.get('claim_id'),
            publisher_id=review_data.get('publisher_id'),
            appearance_ids=set(review_data.get('appearance_ids', [])),
            stage=review_data.get('stage', 0),
            dismissed=review_data.get('dismissed', False),
            dismissed_reason=review_data.get('dismissed_reason'),
        )

        # Link article and publisher
        review._article_obj = articles_by_url.get(str(review.url))
        if review.publisher_id:
            review._publisher_obj = publishers_by_id.get(review.publisher_id)

        # Link appearances
        review._appearances_list = [
            appearances_by_id[aid] for aid in review.appearance_ids
            if aid in appearances_by_id
        ]

        reviews_by_id[review.id] = review

    # Build claims
    claims_by_id = {}
    for claim_data in pipeline_data.get('claims', []):
        claim = InMemoryClaim(
            id=claim_data['id'],
            data=claim_data['data'],
            date=parse_date(claim_data.get('date')),
            appearance_ids=set(claim_data.get('appearance_ids', [])),
            review_ids=set(claim_data.get('review_ids', [])),
            verdict_ids=set(claim_data.get('verdict_ids', [])),
            quality_check=claim_data.get('quality_check'),
            quality_check_reasoning=claim_data.get('quality_check_reasoning'),
        )

        # Link reviews
        claim._reviews_list = [
            reviews_by_id[rid] for rid in claim.review_ids
            if rid in reviews_by_id
        ]

        # Link appearances
        claim._appearances_list = [
            appearances_by_id[aid] for aid in claim.appearance_ids
            if aid in appearances_by_id
        ]

        claims_by_id[claim.id] = claim

    logger.info(f"Built {len(claims_by_id)} claims with full context")
    return claims_by_id


