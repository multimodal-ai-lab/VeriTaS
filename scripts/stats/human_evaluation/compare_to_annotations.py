async def predict_verdicts_in_memory(claims: list[InMemoryClaim]) -> dict[int, Verdict]:
    """
    Run stage 6 verdict prediction on in-memory claims.

    Args:
        claims: List of InMemoryClaim instances

    Returns:
        Dictionary mapping claim_id to Verdict
    """
    logger.info(f"Predicting verdicts for {len(claims)} claims")

    # Temporarily replace Verdict class to capture results
    verdicts_by_claim = {}
    next_verdict_id = 1

    # Monkey-patch Verdict.save_to_db to capture verdicts and assign IDs
    original_save = Verdict.save_to_db

    async def capture_verdict(self):
        nonlocal next_verdict_id
        if self.claim_id:
            # Assign an ID to the verdict so the linking logic works
            if self.id is None:
                self.id = next_verdict_id
                next_verdict_id += 1
            verdicts_by_claim[self.claim_id] = self

    Verdict.save_to_db = capture_verdict

    try:
        # Run prediction
        await predict_verdicts(set(claims))
    except Exception as e:
        logger.error(f"Error during prediction: {e}", exc_info=True)
    finally:
        # Restore original method
        Verdict.save_to_db = original_save

    logger.info(f"Successfully predicted verdicts for {len(verdicts_by_claim)} claims")
    return verdicts_by_claim


