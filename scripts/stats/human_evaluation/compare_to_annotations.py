def extract_label_value(label_data: dict | None) -> tuple[str | None, float | None]:
    """Extract the value and confidence from a label/attribute."""
    if not label_data:
        return None, None
    return label_data.get('value'), label_data.get('confidence')


def compare_labels(automated: Any, human: dict | None, property_name: str) -> dict:
    """
    Compare an automated label with a human annotation.

    Args:
        automated: Automated label (LabelAggregated or similar)
        human: Human annotation dictionary
        property_name: Name of the property being compared

    Returns:
        Comparison dictionary
    """
    # Extract individual model labels if available (for ensemble analysis)
    # Do this first, so it's available even when human annotation is missing
    individual_model_labels = None
    if automated and hasattr(automated, 'individual_labels'):
        individual_model_labels = [
            {
                'model': label.rater,
                'tendency': label.score,
                'explanation': label.explanation if hasattr(label, 'explanation') else None,
            }
            for label in automated.individual_ratings
        ]

    if human is None:
        return {
            'property': property_name,
            'automated_value': getattr(automated, 'tendency', None) if automated else None,
            'automated_explanation': getattr(automated, 'explanation', None) if automated else None,
            'automated_individual_models': individual_model_labels,
            'human_value': None,
            'human_confidence': None,
            'agreement': None,
            'note': 'No human annotation'
        }

    human_value, human_confidence = extract_label_value(human)

    # Get automated tendency
    automated_tendency = getattr(automated, 'tendency', None) if automated else None

    # Determine agreement
    # For now, simple comparison: positive (>0), negative (<0), unknown (0)
    agreement = None
    if automated_tendency is not None and human_value is not None:
        automated_category = 'positive' if automated_tendency > 0 else ('negative' if automated_tendency < 0 else 'unknown')
        human_category = human_value.lower()

        # Map human values to categories
        # This is a simplified mapping - may need refinement based on schema
        if 'unknown' in human_category:
            human_cat = 'unknown'
        elif human_category in ['clear', 'pristine', 'correct', 'true', 'sufficient', 'legitimate', 'intact']:
            human_cat = 'positive'
        else:
            human_cat = 'negative'

        agreement = automated_category == human_cat

    # Note: individual_model_labels already extracted at the beginning of this function

    return {
        'property': property_name,
        'automated_tendency': automated_tendency,
        'automated_explanation': getattr(automated, 'explanation', None) if automated else None,
        'automated_individual_models': individual_model_labels,
        'human_value': human_value,
        'human_confidence': human_confidence,
        'agreement': agreement,
    }


def compare_media_evaluations(automated_media: list, human_media: dict) -> list[dict]:
    """Compare automated media verdicts with human media evaluations."""
    comparisons = []

    for media_verdict in automated_media:
        media_id = str(media_verdict.reference)
        human_eval = human_media.get(media_id, {})

        if human_eval.get('dismissed'):
            comparisons.append({
                'media_id': media_id,
                'note': 'Human annotator dismissed this media',
                'authenticity': None,
                'contextualization': None,
            })
            continue

        auth_comparison = compare_labels(
            media_verdict.authenticity,
            human_eval.get('media_authenticity'),
            'authenticity'
        )

        context_comparison = compare_labels(
            media_verdict.contextualization,
            human_eval.get('media_contextualization'),
            'contextualization'
        )

        comparisons.append({
            'media_id': media_id,
            'authenticity': auth_comparison,
            'contextualization': context_comparison,
        })

    return comparisons


def compare_single_annotation(verdict: Verdict, annotation: dict) -> dict:
    """Compare a single automated verdict with a single human annotation."""

    if annotation.get('dismissed'):
        return {
            'annotation_id': annotation['annotation_id'],
            'dismissed': True,
            'dismiss_reason': annotation.get('dismiss_reason'),
            'comparisons': None,
        }

    claim_level = annotation.get('claim_level', {})

    # Compare claim-level properties
    comparisons = {
        'clarity': compare_labels(verdict.clarity, claim_level.get('clarity'), 'clarity'),
        'veracity': compare_labels(verdict.veracity, claim_level.get('veracity'), 'veracity'),
        'context_coverage': compare_labels(verdict.context_coverage, claim_level.get('context_coverage'), 'context_coverage'),
        'intent': compare_labels(verdict.intent, claim_level.get('intent'), 'intent'),
    }

    # Compare media evaluations
    human_media = annotation.get('media_evaluations', {})
    comparisons['media'] = compare_media_evaluations(verdict.media_verdicts, human_media)

    return {
        'annotation_id': annotation['annotation_id'],
        'annotator': annotation['annotator'],
        'dismissed': False,
        'comparisons': comparisons,
    }


def _value_to_sign(prop: str, value: str | None) -> float:
    """Convert property value to polarity sign."""
    if not value:
        return 0.0
    v = str(value).strip().lower()

    if prop == "clarity":
        return +1.0 if v == "clear" else (-1.0 if v == "ambiguous" else 0.0)
    elif prop == "veracity":
        return +1.0 if v == "true" else (-1.0 if v == "false" else 0.0)
    elif prop == "context_coverage":
        return +1.0 if v == "sufficient" else (-1.0 if v == "insufficient" else 0.0)
    elif prop == "intent":
        return +1.0 if v == "legitimate" else (-1.0 if v == "illegitimate" else 0.0)
    return 0.0


def _to_tendency(prop: str, label_obj: dict | None) -> float | None:
    """Convert value + confidence to tendency in [-1, 1]."""
    if not label_obj or not isinstance(label_obj, dict):
        return None

    value = label_obj.get('value')
    confidence = label_obj.get('confidence')

    if value is None:
        return None

    sign = _value_to_sign(prop, value)
    magnitude = (confidence / 3.0) if confidence is not None else 0.0
    magnitude = max(0.0, min(1.0, magnitude))

    return sign * magnitude


def aggregate_annotations(annotations: list[dict]) -> dict:
    """Aggregate multiple human annotations using tendency-based averaging.

    Converts each annotation (value + confidence) to a tendency [-1, 1],
    then averages across all annotations for each property.
    """
    if not annotations:
        return {}

    # Collect tendencies for each property
    tendencies = defaultdict(list)

    for ann in annotations:
        if ann.get('dismissed'):
            continue

        claim_level = ann.get('claim_level', {})
        for prop in ['clarity', 'veracity', 'context_coverage', 'intent']:
            if prop in claim_level:
                tendency = _to_tendency(prop, claim_level[prop])
                if tendency is not None:
                    tendencies[prop].append(tendency)

    # Average tendencies for each property
    aggregated = {}
    for prop, vals in tendencies.items():
        if vals:
            avg_tendency = sum(vals) / len(vals)
            aggregated[prop] = {'tendency': avg_tendency, 'n': len(vals)}

    return aggregated


def compare_tendencies(automated_label, human_agg: dict | None, property_name: str) -> dict:
    """
    Compare automated label tendency with aggregated human tendency.

    Args:
        automated_label: Automated label (LabelAggregated or similar)
        human_agg: Aggregated human annotation with 'tendency' and 'n' keys
        property_name: Name of the property being compared

    Returns:
        Comparison dictionary with tendency-based metrics
    """
    auto_tendency = getattr(automated_label, 'tendency', None) if automated_label else None

    # Extract individual model labels if available (for ensemble analysis)
    individual_model_labels = None
    if automated_label and hasattr(automated_label, 'individual_labels'):
        individual_model_labels = [
            {
                'model': label.rater,
                'tendency': label.score,
            }
            for label in automated_label.individual_ratings
        ]

    if human_agg is None or 'tendency' not in human_agg:
        return {
            'property': property_name,
            'automated_tendency': auto_tendency,
            'automated_individual_models': individual_model_labels,
            'human_tendency': None,
            'human_n': 0,
            'difference': None,
            'agreement': None,
            'note': 'No human annotation'
        }

    human_tendency = human_agg['tendency']
    human_n = human_agg.get('n', 0)

    # Calculate difference
    if auto_tendency is not None and human_tendency is not None:
        difference = abs(auto_tendency - human_tendency)

        # Determine agreement (same sign or both near zero)
        auto_sign = 1 if auto_tendency > 0.1 else (-1 if auto_tendency < -0.1 else 0)
        human_sign = 1 if human_tendency > 0.1 else (-1 if human_tendency < -0.1 else 0)
        agreement = auto_sign == human_sign

    else:
        difference = None
        agreement = None

    return {
        'property': property_name,
        'automated_tendency': auto_tendency,
        'automated_individual_models': individual_model_labels,
        'human_tendency': human_tendency,
        'human_n': human_n,
        'difference': difference,
        'agreement': agreement,
    }


def compare_claim(claim_id: int, verdict: Verdict | None, annotations: list[dict]) -> dict:
    """
    Compare automated verdict with human annotations for a single claim.

    Args:
        claim_id: Claim ID
        verdict: Automated verdict (or None if prediction failed)
        annotations: List of human annotation dictionaries

    Returns:
        Comparison dictionary
    """
    result = {
        'claim_id': claim_id,
        'verdict_available': verdict is not None,
        'num_annotations': len(annotations),
        'individual_comparisons': [],
        'aggregated_comparison': None,
    }

    if not verdict:
        result['note'] = 'Verdict prediction failed'
        return result

    # Compare with each individual annotation
    for annotation in annotations:
        comparison = compare_single_annotation(verdict, annotation)
        result['individual_comparisons'].append(comparison)

    # Compare with aggregated annotations (tendency-based)
    aggregated = aggregate_annotations(annotations)
    if aggregated:
        result['aggregated_comparison'] = {
            'clarity': compare_tendencies(verdict.clarity, aggregated.get('clarity'), 'clarity'),
            'veracity': compare_tendencies(verdict.veracity, aggregated.get('veracity'), 'veracity'),
            'context_coverage': compare_tendencies(verdict.context_coverage, aggregated.get('context_coverage'), 'context_coverage'),
            'intent': compare_tendencies(verdict.intent, aggregated.get('intent'), 'intent'),
        }

    return result


def calculate_summary_statistics(comparisons: list[dict]) -> dict:
    """Calculate summary statistics using aggregated (tendency-based) comparisons."""
    total_claims = len(comparisons)
    claims_with_verdicts = sum(1 for c in comparisons if c['verdict_available'])
    total_annotations = sum(c['num_annotations'] for c in comparisons)

    # Count agreements for each property using aggregated comparisons
    property_stats = defaultdict(lambda: {
        'total': 0,
        'agreements': 0,
        'disagreements': 0,
        'no_data': 0,
        'mean_abs_difference': [],
        'automated_certainties': [],
        'human_certainties': [],
    })

    for comparison in comparisons:
        if not comparison['verdict_available']:
            continue

        agg_comp = comparison.get('aggregated_comparison', {})
        if not agg_comp:
            continue

        for prop in ['clarity', 'veracity', 'context_coverage', 'intent']:
            if prop in agg_comp:
                comp = agg_comp[prop]

                if comp.get('human_tendency') is None:
                    property_stats[prop]['no_data'] += 1
                    continue

                property_stats[prop]['total'] += 1

                if comp.get('agreement') is True:
                    property_stats[prop]['agreements'] += 1
                elif comp.get('agreement') is False:
                    property_stats[prop]['disagreements'] += 1

                # Track absolute difference in tendencies
                if comp.get('difference') is not None:
                    property_stats[prop]['mean_abs_difference'].append(comp['difference'])

                # Track certainty (absolute value of tendency)
                auto_tendency = comp.get('automated_tendency')
                human_tendency = comp.get('human_tendency')

                if auto_tendency is not None:
                    property_stats[prop]['automated_certainties'].append(abs(auto_tendency))
                if human_tendency is not None:
                    property_stats[prop]['human_certainties'].append(abs(human_tendency))

    # Calculate agreement rates and mean absolute differences
    agreement_rates = {}
    mean_differences = {}
    automated_certainties = {}
    human_certainties = {}

    for prop, stats in property_stats.items():
        if stats['total'] > 0:
            agreement_rates[prop] = stats['agreements'] / stats['total']
        else:
            agreement_rates[prop] = None

        if stats['mean_abs_difference']:
            mean_differences[prop] = sum(stats['mean_abs_difference']) / len(stats['mean_abs_difference'])
        else:
            mean_differences[prop] = None

        # Calculate mean certainties
        if stats['automated_certainties']:
            automated_certainties[prop] = sum(stats['automated_certainties']) / len(stats['automated_certainties'])
        else:
            automated_certainties[prop] = None

        if stats['human_certainties']:
            human_certainties[prop] = sum(stats['human_certainties']) / len(stats['human_certainties'])
        else:
            human_certainties[prop] = None

    return {
        'total_claims': total_claims,
        'claims_with_verdicts': claims_with_verdicts,
        'claims_with_failed_verdicts': total_claims - claims_with_verdicts,
        'total_annotations': total_annotations,
        'property_statistics': dict(property_stats),
        'agreement_rates': agreement_rates,
        'mean_absolute_differences': mean_differences,
        'automated_certainties': automated_certainties,
        'human_certainties': human_certainties,
    }


# ============================================================================
# Main Function
# ============================================================================

async def main():
    """Main comparison function."""
    parser = argparse.ArgumentParser(
        description='Compare human annotations with automated verdicts',
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    parser.add_argument(
        'zip_file',
        type=str,
        help='Path to annotations export zip file'
    )

    parser.add_argument(
        '-o', '--output',
        type=str,
        default=None,
        help='Output JSON file path (default: comparison_results_YYYY-MM-DD.json)'
    )

    parser.add_argument(
        '--limit',
        type=int,
        default=None,
        help='Limit the number of claims to process (for testing)'
    )

    args = parser.parse_args()

    # Validate input
    zip_path = Path(args.zip_file)
    if not zip_path.exists():
        logger.error(f"Zip file not found: {zip_path}")
        sys.exit(1)

    # Set output path
    if args.output:
        output_path = Path(args.output)
    else:
        output_path = Path(f"comparison_results_{datetime.now().strftime('%Y-%m-%d_%H-%M-%S')}.json")

    try:
        # Step 1: Load data from zip
        logger.info("=" * 60)
        logger.info("STEP 1: LOADING DATA")
        logger.info("=" * 60)
        pipeline_data, annotations_data, temp_dir = load_data_from_zip(zip_path)

        # Step 2: Build in-memory object graph
        logger.info("=" * 60)
        logger.info("STEP 2: BUILDING IN-MEMORY OBJECTS")
        logger.info("=" * 60)
        claims_by_id = build_in_memory_objects(pipeline_data, temp_dir)

        # Apply limit if specified
        if args.limit:
            claim_ids = list(claims_by_id.keys())[:args.limit]
            claims_by_id = {cid: claims_by_id[cid] for cid in claim_ids}
            logger.info(f"Limited to {len(claims_by_id)} claims for testing")

        # Step 3: Run verdict prediction
        logger.info("=" * 60)
        logger.info("STEP 3: PREDICTING VERDICTS")
        logger.info("=" * 60)
        verdicts_by_claim = await predict_verdicts_in_memory(list(claims_by_id.values()))

        # Step 4: Compare results
        logger.info("=" * 60)
        logger.info("STEP 4: COMPARING RESULTS")
        logger.info("=" * 60)

        grouped_annotations = annotations_data.get('grouped_by_claim', {})
        comparisons = []

        for claim_id_str, annotations in grouped_annotations.items():
            claim_id = int(claim_id_str)
            verdict = verdicts_by_claim.get(claim_id)

            comparison = compare_claim(claim_id, verdict, annotations)
            comparisons.append(comparison)

        # Calculate summary statistics
        summary = calculate_summary_statistics(comparisons)

        # Step 5: Generate output
        logger.info("=" * 60)
        logger.info("STEP 5: GENERATING OUTPUT")
        logger.info("=" * 60)

        output_data = {
            'metadata': {
                'input_file': str(zip_path),
                'timestamp': datetime.now().isoformat(),
                'script_version': '1.0',
            },
            'summary': summary,
            'per_claim_comparisons': comparisons,
        }

        # Save to JSON
        with open(output_path, 'w') as f:
            json.dump(output_data, f, indent=2, default=str)

        logger.info(f"Results saved to: {output_path}")

        # Print summary
        logger.info("=" * 60)
        logger.info("SUMMARY")
        logger.info("=" * 60)
        logger.info(f"Total claims: {summary['total_claims']}")
        logger.info(f"Claims with verdicts: {summary['claims_with_verdicts']}")
        logger.info(f"Failed predictions: {summary['claims_with_failed_verdicts']}")
        logger.info(f"Total annotations: {summary['total_annotations']}")
        logger.info("")
        logger.info("Agreement rates:")
        for prop, rate in summary['agreement_rates'].items():
            if rate is not None:
                logger.info(f"  {prop}: {rate:.2%}")
            else:
                logger.info(f"  {prop}: N/A")
        logger.info("=" * 60)

    except Exception as e:
        logger.error(f"Comparison failed: {e}", exc_info=True)
        sys.exit(1)


if __name__ == '__main__':
    asyncio.run(main())
